import test from "node:test";
import assert from "node:assert/strict";
import { PUBSUB_CHANNELS, createRedisBus } from "@cvm/shared";
import { createApp } from "../src/app.js";

function createFakeRedis() {
  const store = new Map();
  const listeners = [];

  return {
    _store: store,
    async get(key) {
      return store.has(key) ? store.get(key) : null;
    },
    async set(key, value) {
      store.set(key, String(value));
      return "OK";
    },
    async incr(key) {
      const next = (Number.parseInt(store.get(key) || "0", 10) || 0) + 1;
      store.set(key, String(next));
      return next;
    },
    async expire() {
      return 1;
    },
    async subscribe() {
      return 1;
    },
    on(event, cb) {
      if (event === "message") listeners.push(cb);
    },
    emitMessage(channel, payload) {
      const raw = typeof payload === "string" ? payload : JSON.stringify(payload);
      for (const cb of listeners) cb(channel, raw);
    },
  };
}

function createInMemoryStore(prefix) {
  const docs = new Map();
  let seq = 1;

  return {
    _docs: docs,
    async create(payload) {
      const id = `${prefix}-${seq++}`;
      const raw = { createdAt: new Date(), updatedAt: new Date(), ...payload, _id: id };
      docs.set(id, raw);
      return raw;
    },
    async findOne(filter = {}) {
      for (const raw of docs.values()) {
        if (filter.applicationId && raw.applicationId !== filter.applicationId) continue;
        if (filter.targetAudience && raw.targetAudience !== filter.targetAudience) continue;
        if (filter.autoGenerated !== undefined && raw.autoGenerated !== filter.autoGenerated) continue;
        return raw;
      }
      return null;
    },
    async find(filter = {}) {
      const list = [];
      for (const raw of docs.values()) {
        if (filter.applicationId && raw.applicationId !== filter.applicationId) continue;
        if (filter.targetAudience && raw.targetAudience !== filter.targetAudience) continue;
        list.push(raw);
      }
      return list;
    },
  };
}

function listenApp(app) {
  return new Promise((resolve) => {
    const server = app.listen(0, "127.0.0.1", () => {
      resolve({ server, baseUrl: `http://127.0.0.1:${server.address().port}` });
    });
  });
}

test("AI Enrichment enforces recruiter-question RBAC, auto-generates on interview event, caches 1h, falls back, and enforces 10/day quota", async (t) => {
  const fakeRedis = createFakeRedis();
  const redisBus = createRedisBus(fakeRedis);
  const AiGenerationEventModel = createInMemoryStore("ai-evt");
  const InterviewQuestionModel = createInMemoryStore("iq");

  const failingLlmProvider = {
    providerName: "gemini",
    modelName: "gemini-2.0-flash",
    async generateInterviewQuestions() {
      throw new Error("Gemini quota exceeded 429");
    },
    async optimizeCv() {
      throw new Error("Gemini timeout");
    },
    async generateCoverLetter() {
      throw new Error("Gemini timeout");
    },
  };

  const app = createApp({
    AiGenerationEventModel,
    InterviewQuestionModel,
    redisClient: fakeRedis,
    subscriberClient: fakeRedis,
    redisBus,
    llmProvider: failingLlmProvider,
    dailyCandidateQuota: 10,
    gatewaySecret: "gw-secret",
  });

  const { server, baseUrl } = await listenApp(app);
  t.after(() => server.close());

  const candHeaders = {
    "x-gateway-secret": "gw-secret",
    "x-user-id": "cand-1",
    "x-user-role": "candidate",
    "Content-Type": "application/json",
  };
  const recHeaders = {
    "x-gateway-secret": "gw-secret",
    "x-user-id": "rec-1",
    "x-user-role": "recruiter",
    "Content-Type": "application/json",
  };

  // 1. Candidate blocked 403 when requesting targetAudience: "recruiter"
  const forbiddenGen = await fetch(`${baseUrl}/api/interviews/questions`, {
    method: "POST",
    headers: candHeaders,
    body: JSON.stringify({ applicationId: "app-1", targetAudience: "recruiter" }),
  });
  assert.equal(forbiddenGen.status, 403);
  assert.equal((await forbiddenGen.json()).error_code, "forbidden_recruiter_questions");

  // 2. APPLICATION_STATUS_CHANGED (to_status: "interview") auto-generates recruiter questions with template_fallback
  fakeRedis.emitMessage(PUBSUB_CHANNELS.APPLICATION_STATUS_CHANGED, {
    application_id: "app-99",
    job_id: "job-99",
    resume_id: "res-99",
    candidate_id: "cand-1",
    to_status: "interview",
  });
  await new Promise((r) => setTimeout(r, 30));

  const recGet = await fetch(`${baseUrl}/api/interviews/questions/app-99?audience=recruiter`, {
    headers: recHeaders,
  });
  assert.equal(recGet.status, 200);
  const recData = await recGet.json();
  assert.equal(recData.questionSets.length, 1);
  assert.equal(recData.questionSets[0].autoGenerated, true);
  assert.equal(recData.questionSets[0].generationMode, "template_fallback");

  // Candidate blocked from reading recruiter questions on app-99
  const candReadRec = await fetch(`${baseUrl}/api/interviews/questions/app-99?audience=recruiter`, {
    headers: candHeaders,
  });
  assert.equal(candReadRec.status, 403);

  // 3. 1-hour cv_opt cache: 1st call generates (cached: false), 2nd call hits cache (cached: true)
  const opt1 = await fetch(`${baseUrl}/api/enrichment/optimize-cv`, {
    method: "POST",
    headers: candHeaders,
    body: JSON.stringify({
      resumeId: "res-1",
      jobId: "job-1",
      missingKeywords: ["Kubernetes", "Redis"],
    }),
  });
  assert.equal(opt1.status, 200);
  const dOpt1 = await opt1.json();
  assert.equal(dOpt1.cached, false);
  assert.equal(dOpt1.generation_mode, "template_fallback");

  const opt2 = await fetch(`${baseUrl}/api/enrichment/optimize-cv`, {
    method: "POST",
    headers: candHeaders,
    body: JSON.stringify({ resumeId: "res-1", jobId: "job-1" }),
  });
  assert.equal(opt2.status, 200);
  assert.equal((await opt2.json()).cached, true);

  // Verify AiGenerationEvent logged template_fallback
  assert.ok(
    Array.from(AiGenerationEventModel._docs.values()).some(
      (e) => e.generation_mode === "template_fallback"
    )
  );

  // 4. Daily quota (10/day for candidate): 1 already used above -> 9 more succeed, 11th returns 429
  for (let i = 0; i < 9; i += 1) {
    const ok = await fetch(`${baseUrl}/api/enrichment/cover-letter`, {
      method: "POST",
      headers: candHeaders,
      body: JSON.stringify({ jobTitle: `Role ${i}` }),
    });
    assert.equal(ok.status, 200);
  }
  const overQuota = await fetch(`${baseUrl}/api/enrichment/cover-letter`, {
    method: "POST",
    headers: candHeaders,
    body: JSON.stringify({ jobTitle: "Role Over" }),
  });
  assert.equal(overQuota.status, 429);
  assert.equal((await overQuota.json()).error_code, "llm_daily_quota_exceeded");
});
