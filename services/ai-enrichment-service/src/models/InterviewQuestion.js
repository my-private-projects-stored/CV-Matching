import mongoose from "mongoose";

const questionItemSchema = new mongoose.Schema(
  {
    category: { type: String, default: "technical", trim: true },
    question: { type: String, required: true, trim: true },
    expectedSignal: { type: String, default: "", trim: true },
    difficulty: { type: String, enum: ["easy", "medium", "hard"], default: "medium" },
  },
  { _id: false }
);

const interviewQuestionSchema = new mongoose.Schema(
  {
    applicationId: { type: String, default: "", index: true },
    jobId: { type: String, default: "", index: true },
    resumeId: { type: String, default: "", index: true },
    candidateId: { type: String, default: "", index: true },
    recruiterId: { type: String, default: "" },
    targetAudience: {
      type: String,
      enum: ["candidate", "recruiter"],
      required: true,
      index: true,
    },
    language: {
      type: String,
      enum: ["vi", "en"],
      default: "vi",
    },
    questions: {
      type: [questionItemSchema],
      default: [],
    },
    generationMode: {
      type: String,
      enum: ["llm", "template_fallback"],
      default: "template_fallback",
    },
    autoGenerated: {
      type: Boolean,
      default: false,
    },
  },
  {
    timestamps: true,
    collection: "interview_questions",
  }
);

interviewQuestionSchema.index({ applicationId: 1, targetAudience: 1 });

const InterviewQuestion =
  mongoose.models.InterviewQuestion || mongoose.model("InterviewQuestion", interviewQuestionSchema);
export default InterviewQuestion;
